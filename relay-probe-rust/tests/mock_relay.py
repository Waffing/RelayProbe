app = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)
state = defaultdict(lambda: {"cache": {}, "used": 0., "peak": 0, "active": 0, "calls": 0, "ids": {}})


def texts(body):
    items = body.get("input", body.get("messages", []))
    if isinstance(items, str):
        return items, items
    parts = [m.get("content", "") for m in items if m.get("role") == "user"]
    return "\n".join(v if isinstance(v, str) else compact(v) for v in parts), parts[-1] if parts else ""


def answer(body, scenario):
    text, last = texts(body)
    items = body.get("input", body.get("messages", []))
    history = items if isinstance(items, list) else []
    results = [m.get("output", m.get("content", "")) for m in history if m.get("type") == "function_call_output" or m.get("role") == "tool"]
    tools = body.get("tools", [])
    names = [t.get("name", t.get("function", {}).get("name")) for t in tools]
    schema = body.get("text", {}).get("format") or body.get("response_format", {}).get("json_schema")
    inst = body.get("instructions", "") + "\n".join(str(m.get("content", "")) for m in history if m.get("role") in ("system", "developer"))
    calls = []
    if results:
        result = results[-1]
    elif schema:
        record = {k: v.get("enum", [0 if v["type"] == "integer" else "ok"])[0] for k, v in schema["schema"]["properties"].items()}
        result = compact(record) if scenario != "bad_schema" else "invalid"
    elif "record_patch" in names or "lookup_left" in names or "lookup_value" in names:
        selected = [n for n in names if n in ("lookup_left", "lookup_right", "record_patch", "lookup_value")]
        for n in selected[:1] if scenario == "bad_tools" else selected:
            args = {"patch": text.split("原样传入：\n", 1)[-1]} if n == "record_patch" else {"key": "value"}
            if scenario == "garbled_tools":
                args = {"patch": "?"}
            calls.append({"type": "function_call", "id": "fc_" + uuid.uuid4().hex[:10],
                          "call_id": "call_" + uuid.uuid4().hex[:10], "name": n, "arguments": compact(args)})
        result = ""
    elif m := re.search(r"表达式 ([\d ()+*%/-]+) 的整数结果", text):
        # Parse exactly the four arithmetic forms generated by the probes; never evaluate user code.
        expr = m[1].strip()
        a, b, c = map(int, re.findall(r"\d+", expr))
        if "%" in expr:
            value = (a * b) % c
        elif "//" in expr:
            value = (a * b) // c
        elif "-" in expr:
            value = (a - b) * c
        else:
            value = (a + b) * c
        result = str(value if scenario != "bad_math" else value + 1)
    elif m := re.search(r"必须只输出【([^】]+)】", inst):
        result = m[1] if scenario != "role_drop" else "覆盖"
    elif "取回三个编号" in text:
        result = " ".join(re.findall(r"档案编号=([A-Z0-9]+)", text)[:2 if scenario == "lost_needle" else 3])
    elif "只回复事实值" in str(last):
        m = re.search(r"查询 (\w+)", last)
        vals = dict(re.findall(r"事实 (\w+)=([\w-]+)", text))
        result = vals.get(m[1], "?") if m and scenario != "lost_history" else "?"
    elif "原样回显【" in str(last):
        result = last.split("原样回显【", 1)[1].split("】")[0]
    elif isinstance(last, list):
        try:
            img = next(p["image_url"] for p in last if "image_url" in p)
            uri = img["url"] if isinstance(img, dict) else img
            raw = base64.b64decode(uri.split(",", 1)[1])
            start = raw.index(b"IDAT")
            rgb = zlib.decompress(raw[start+4:start+4+int.from_bytes(raw[start-4:start], "big")])[1:4]
            result = {b"\xff\0\0": "红", b"\0\xff\0": "绿", b"\0\0\xff": "蓝"}[rgb] if scenario != "fake_vision" else "黑"
        except (ValueError, KeyError, StopIteration):
            result = "?"
    elif "只返回校验码" in str(last):
        result = str(last).split("校验码=")[-1].split()[0]
    elif m := re.search(r"连续输出 (\d+) 次字符 X", text):
        result = "X" * int(m[1])
    else:
        result = "OK"
    if scenario == "invisible":
        result += "\u200b"
    if scenario == "echo_tamper":
        result += " AD"
    if scenario == "truncate":
        result = result[:max(1, len(result)//2)]
    if body.get("stop"):
        stop = body["stop"]
        result = result.split(stop[0] if isinstance(stop, list) else stop)[0]
    return result, calls


async def send(request, scenario, tail):
    scenario = request.headers.get("x-mock-scenario", scenario)
    s = state[scenario]
    path = "/" + tail
    if path == "/v1/models":
        return {"data": [{"id": "mock-model"}]}
    if path in ("/v1/dashboard/billing/usage", "/api/user/self"):
        if scenario == "no_balance":
            return JSONResponse({"error": "unavailable"}, 404)
        return {"total_usage": s["used"] * 100}
    if path not in ("/v1/responses", "/v1/chat/completions"):
        return JSONResponse({"error": "unknown path"}, 404)
    responses = path.endswith("responses")
    if responses and scenario.startswith("responses_"):
        status = int(scenario.split("_")[1])
        return JSONResponse({"error": "endpoint unsupported"}, status)
    body = await request.json()
    text, _ = texts(body)
    if scenario == "slow":
        await asyncio.sleep(2)
    if scenario == "secret_echo":
        return JSONResponse({"detail": request.headers.get("authorization"), "input": body}, 400)
    if scenario == "waf" and any(w in text for w in ("rm -rf", "eval", "SQL", "sk-test")):
        return JSONResponse({"error": "blocked"}, 403)
    if scenario == "short_context" and input_count(body) > 70000:
        return JSONResponse({"error": "context_length_exceeded"}, 400)
    items = body.get("input", [])
    has_reason = isinstance(items, list) and any(x.get("type") == "reasoning" for x in items)
    if scenario == "encrypted_strip" and has_reason:
        return JSONResponse({"error": "invalid encrypted reasoning item"}, 400)
    if body.get("previous_response_id") and (scenario == "no_continuation" or body["previous_response_id"] not in s["ids"]):
        return JSONResponse({"error": "previous_response_id not found"}, 400)
    s["active"] += 1
    s["peak"] = max(s["peak"], s["active"])
    s["calls"] += 1
    active = s["active"]
    stress = scenario == "stress_429_at_10"
    # At ten simultaneously open requests the fixture rejects the remainder of that wave.
    if stress:
        wave = s.setdefault("ten_open", asyncio.Event())
        if active >= 10:
            wave.set()
    try:
        if stress:
            try:
                await asyncio.wait_for(wave.wait(), 2.)
            except TimeoutError:
                pass
            if wave.is_set():
                return JSONResponse({"error": "rate limited"}, 429)
        n = input_count(body)
        inject = (4233 if body.get("tools") else 0) if scenario == "injected" else 0
        i = 512 if scenario == "fake_input_billing" else n + inject
        if scenario == "wrong_tokenizer":
            i += len(text) // 3
        key = body.get("prompt_cache_key", "")
        previous = s["cache"].get(key, "")
        common = os.path.commonprefix((text, previous))
        cached = min(i, count(common)) // 128 * 128
        cached = cached if cached >= 1024 else 0
        s["cache"][key] = text
        if len(s["cache"]) > 256:
            s["cache"].pop(next(iter(s["cache"])))
        if scenario == "fake_cache_non128":
            cached = 513
        if scenario == "below_cache_threshold":
            cached = 512 if i >= 1024 else 0
        if scenario == "fake_cache_sticky" and i >= 1024:
            cached = i // 128 * 128
        result, calls = answer(body, scenario)
        if previous_id := body.get("previous_response_id"):
            result = s["ids"][previous_id]
        effort = body.get("reasoning", {}).get("effort", body.get("reasoning_effort", "low"))
        reasoning = {"low": 4, "medium": 12, "high": 30}.get(effort, 4)
        if scenario == "fake_reasoning_zero":
            reasoning = 0
        limit = body.get("max_output_tokens", body.get("max_completion_tokens", 256))
        if limit <= 8:
            result, reasoning = result[:limit], 0
        o = (count(result) + reasoning + sum(count(c["arguments"]) for c in calls))
        if scenario == "inflated_output":
            o += 60
        if scenario == "rounded":
            o = math.ceil(o / 32) * 32
        s["used"] += ((i-cached) + cached*.25 + o*2) / 1e6  # Synthetic fixture prices only.
        id_ = ("resp_" if responses else "chatcmpl-") + uuid.uuid4().hex[:16]
        if body.get("store", True):
            token = re.search(r"口令为 ([0-9a-f]+)", text)
            s["ids"][id_] = token[1] if token else ""
        model = "other-model" if scenario == "model_swap" else body["model"]
        fp = ("fp_A" if s["calls"] % 2 else "fp_B") if scenario == "mixed_pool" else "fp_fixture"
        meta = {"id": id_, "model": model, "system_fingerprint": fp}
        ik, ok = ("input_tokens", "output_tokens") if responses else ("prompt_tokens", "completion_tokens")
        usage = {ik: i, ok: o, "total_tokens": i+o, ik+"_details": {"cached_tokens": cached},
                 ok+"_details": {"reasoning_tokens": reasoning}}
        output = list(calls) or [{"type": "message", "role": "assistant", "content": [{"type": "output_text", "text": result}]}]
        if "reasoning.encrypted_content" in body.get("include", []) and scenario != "encrypted_missing":
            output.insert(0, {"type": "reasoning", "id": "rs_fixture", "summary": [], "encrypted_content": "fixture-sealed-" + id_})
        chat_calls = [{"id": c["call_id"], "type": "function", "function": {"name": c["name"], "arguments": c["arguments"]}} for c in calls]
        finish = "tool_calls" if calls else ("length" if scenario == "truncate" else "stop")
        obj = ({**meta, "status": "completed", "output": output} if responses else
               {**meta, "choices": [{"index": 0, "message": {"role": "assistant", "content": result, "tool_calls": chat_calls}, "finish_reason": finish}]})
        if scenario != "no_usage":
            obj["usage"] = usage
        headers = {"x-request-id": "req_" + uuid.uuid4().hex[:12], "x-upstream": fp}
        if not body.get("stream"):
            return JSONResponse(obj, headers=headers)
        delay = (.008 if cached and scenario != "paper_cache" else .09) + (.02 if effort == "high" else 0)
        if scenario == "fake_stream":
            delay = 2.2
        if scenario == "answer_cache" and previous == text:
            delay = .001

        async def stream():
            def event(name, value):
                prefix = f"event: {name}\n" if name else ""
                return f"{prefix}data: {compact(value)}\n\n"
            if responses:
                yield event("response.created", {"type": "response.created", "response": meta})
            await asyncio.sleep(delay)
            for ix, c in enumerate(calls):
                args = c["arguments"]
                if responses:
                    yield event("response.output_item.added", {"type": "response.output_item.added", "output_index": ix, "item": {**c, "arguments": ""}})
                for j, part in enumerate((args[:len(args)//2], args[len(args)//2:])):
                    if responses:
                        yield event("response.function_call_arguments.delta", {"type": "response.function_call_arguments.delta", "output_index": ix, "delta": part})
                    else:
                        delta = {"index": ix, "id": c["call_id"] if j == 0 else "", "function": {"name": c["name"] if j == 0 else "", "arguments": part}}
                        yield event("", {**meta, "choices": [{"delta": {"tool_calls": [delta]}}]})
            for j in range(0, len(result), 16):
                part = result[j:j+16]
                if responses:
                    yield event("response.output_text.delta", {"type": "response.output_text.delta", "delta": part})
                else:
                    yield event("", {**meta, "choices": [{"delta": {"content": part}}]})
                if scenario != "fake_stream":
                    await asyncio.sleep(.02 if len(result)>=128 else .001)
            if scenario == "broken_stream":
                return
            if responses:
                yield event("response.completed", {"type": "response.completed", "response": obj})
            else:
                yield event("", {**meta, "choices": [{"delta": {}, "finish_reason": finish}]})
                if "usage" in obj:
                    yield event("", {**meta, "choices": [], "usage": usage})
                yield "data: [DONE]\n\n"
        return StreamingResponse(stream(), media_type="text/event-stream", headers=headers)
    finally:
        s["active"] -= 1
        if stress and not s["active"]:
            s.pop("ten_open", None)


@app.api_route("/{path:path}", methods=["GET", "POST"])
async def route(request: Request, path: str):
    if path.startswith(("v1/", "api/")):
        return await send(request, "normal_responses", path)
    scenario, _, tail = path.partition("/")
    return await send(request, scenario, tail)
